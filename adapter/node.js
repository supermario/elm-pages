import * as fs from "fs";
import * as path from "path";

/**
 * Node.js HTTP server adapter for elm-pages.
 *
 * Generates a standalone Node.js HTTP server that supports streaming request
 * bodies and streaming responses. This is the recommended adapter for
 * production use when handling large file uploads or downloads, since
 * serverless adapters (like Netlify) buffer the entire request body before
 * your code runs.
 *
 * The generated server:
 * - Serves pre-rendered static files from `dist/`
 * - Routes server-rendered pages and API routes through elm-pages
 * - Streams request bodies for ApiRoute.serverRenderStreaming routes: the body
 *   is never held in memory, Stream.requestBody reads it straight off the socket
 * - Buffers request bodies for every other route, the same as the dev server,
 *   so Request.body / form posts keep working (capped by ELM_PAGES_MAX_BODY_BYTES)
 * - Streams Server.Response.streaming responses
 *
 * Output: server/index.mjs (the entry point) and server/elm-pages-cli.mjs (the
 * render bundle). The server reads static files from ../dist relative to its own
 * file, so server/ and dist/ can be moved together (e.g. into a release dir).
 *
 * Environment: PORT (default 3000), HOST (default: all interfaces, IPv4 and
 * IPv6, like the dev server), ELM_PAGES_MAX_BODY_BYTES (default 128MB),
 * ELM_PAGES_DIST_DIR (override the static file dir).
 *
 * `node server/index.mjs --check` loads the render bundle and exits without
 * listening, to verify a build before switching to it.
 */
export default async function run({
  renderFunctionFilePath,
  routePatterns,
  apiRoutePatterns,
}) {
  console.log("Running Node.js server adapter");
  ensureDirSync("server");

  fs.copyFileSync(renderFunctionFilePath, "./server/elm-pages-cli.mjs");
  fs.writeFileSync(
    "./server/index.mjs",
    serverCode({ routePatterns, apiRoutePatterns })
  );
  console.log(
    "Node.js server generated at server/index.mjs. Start with: node server/index.mjs"
  );
}

/**
 * Regex sources for the API routes, in route order, mirroring how elm-pages
 * matches them (src/ApiRoute.elm: "^" ++ pattern ++ "$" against the path
 * without its leading slash, first match wins; literals are used as-is and a
 * capture is "(.*)").
 */
function apiRouteMatchers(apiRoutePatterns) {
  return (apiRoutePatterns || []).map((route) => ({
    kind: route.kind,
    source: "^" + route.pathPattern.map(segmentToRegex).join("/") + "$",
  }));
}

function segmentToRegex(segment) {
  if (segment.kind === "literal") {
    return segment.value;
  } else if (segment.kind === "dynamic") {
    return "(.*)";
  } else if (segment.kind === "hybrid") {
    return segment.value.map(segmentToRegex).join("");
  } else {
    throw new Error("Unknown API route segment kind: " + segment.kind);
  }
}

/**
 * Page routes take precedence over API routes for non-file paths
 * (src/RenderRequest.elm), so a path a page route claims is never a streaming
 * API route.
 */
function pageRouteMatchers(routePatterns) {
  return (routePatterns || []).map((route) => {
    const segments = route.pathPattern
      .split("/")
      .filter((segment) => segment !== "")
      .map((segment) => {
        if (segment === "*") {
          return "(?:/.*)?";
        } else if (segment.startsWith(":") && segment.endsWith("?")) {
          return "(?:/[^/]+)?";
        } else if (segment.startsWith(":")) {
          return "/[^/]+";
        } else {
          return "/" + segment.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        }
      });
    return { source: "^" + (segments.join("") || "/") + "/?$" };
  });
}

function serverCode({ routePatterns, apiRoutePatterns }) {
  return `// Generated by the elm-pages Node.js adapter. Do not edit.
import * as http from "node:http";
import * as path from "node:path";
import * as fs from "node:fs";
import { randomUUID } from "node:crypto";
import { register } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const SERVER_DIR = path.dirname(fileURLToPath(import.meta.url));
const DIST_DIR = path.resolve(
  process.env.ELM_PAGES_DIST_DIR || path.join(SERVER_DIR, "..", "dist")
);
const PORT = parseInt(process.env.PORT || "3000", 10);
const HOST = process.env.HOST || undefined;
const MAX_BODY_BYTES = parseInt(
  process.env.ELM_PAGES_MAX_BODY_BYTES || String(128 * 1024 * 1024),
  10
);

const API_ROUTES = ${JSON.stringify(apiRouteMatchers(apiRoutePatterns))}.map(
  (route) => ({ kind: route.kind, regex: safeRegex(route.source) })
);
const PAGE_ROUTES = ${JSON.stringify(pageRouteMatchers(routePatterns))}.map(
  (route) => ({ regex: safeRegex(route.source) })
);

function safeRegex(source) {
  try {
    return new RegExp(source);
  } catch (error) {
    return /(?!)/;
  }
}

// The render bundle keeps elm-pages' own dependencies external, so they must
// resolve from wherever this file lives. With elm-pages installed from npm they
// are hoisted next to it and that just works; with a linked elm-pages (file:
// dependency, or npm link) they live in the link target's node_modules, which
// is not on this file's resolution path. Fall back to resolving bare imports
// from the elm-pages package itself.
const elmPagesPackageDir = findElmPagesPackageDir(SERVER_DIR);
if (elmPagesPackageDir) {
  const hooks = \`
let fallbackParentURL = null;
export async function initialize(data) {
  fallbackParentURL = data.fallbackParentURL;
}
export async function resolve(specifier, context, nextResolve) {
  try {
    return await nextResolve(specifier, context);
  } catch (error) {
    const bare = !/^[./]/.test(specifier) && !specifier.includes(":");
    if (bare && fallbackParentURL && error && error.code === "ERR_MODULE_NOT_FOUND") {
      return nextResolve(specifier, { ...context, parentURL: fallbackParentURL });
    }
    throw error;
  }
}
\`;
  register("data:text/javascript," + encodeURIComponent(hooks), {
    parentURL: import.meta.url,
    data: {
      fallbackParentURL: pathToFileURL(
        path.join(elmPagesPackageDir, "package.json")
      ).href,
    },
  });
}

function findElmPagesPackageDir(fromDir) {
  let dir = fromDir;
  while (true) {
    const candidate = path.join(dir, "node_modules", "elm-pages", "package.json");
    if (fs.existsSync(candidate)) {
      return fs.realpathSync(path.dirname(candidate));
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      return null;
    }
    dir = parent;
  }
}

const elmPages = await import("./elm-pages-cli.mjs");

if (process.argv.includes("--check")) {
  console.log("elm-pages server: render bundle loaded OK");
  process.exit(0);
}

const MIME_TYPES = {
  ".html": "text/html", ".js": "application/javascript", ".mjs": "application/javascript",
  ".css": "text/css", ".json": "application/json", ".png": "image/png",
  ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".gif": "image/gif",
  ".svg": "image/svg+xml", ".ico": "image/x-icon", ".xml": "application/xml",
  ".txt": "text/plain", ".woff": "font/woff", ".woff2": "font/woff2",
  ".webp": "image/webp", ".wasm": "application/wasm",
};

const server = http.createServer((req, res) => {
  handleRequest(req, res).catch((error) => {
    console.error("Request failed:", req.method, req.url, error);
    sendError(req, res, error);
  });
});

// Node's default requestTimeout (5 minutes for the WHOLE request) would cut off
// a large upload on a slow link half way. Streaming routes rely on the socket
// staying open for as long as the body keeps arriving.
server.requestTimeout = 0;

async function handleRequest(req, res) {
  const url = new URL(req.url || "/", \`http://\${req.headers.host || "localhost"}\`);
  const pathname = url.pathname;

  if ((req.method === "GET" || req.method === "HEAD") && serveStatic(req, res, pathname)) {
    return;
  }

  const canStream = ["POST", "PUT", "PATCH"].includes(req.method);
  if (canStream && isStreamingRoute(pathname)) {
    // Zero-copy: the request stream is handed to Stream.requestBody as-is.
    const requestId = randomUUID();
    elmPages.registerRequestBodyStream(requestId, req);
    try {
      await elmPages.runWithRequestContext({ requestId }, async () => {
        const renderResult = await elmPages.render(buildRequest(req, null, null));
        await sendResponse(renderResult, req, res);
      });
    } finally {
      elmPages.unregisterRequestBodyStream(requestId);
    }
    return;
  }

  // Everything else gets its body buffered, as the dev server does, so that
  // Request.body (a pure accessor) and form posts see it.
  const bodyBuffer = await readBody(req, res);
  if (bodyBuffer === undefined) {
    return; // too large, already answered
  }
  const serverRequest = await buildRequestWithBody(req, bodyBuffer);
  await elmPages.runWithRequestContext({ requestId: null }, async () => {
    const renderResult = await elmPages.render(serverRequest);
    await sendResponse(renderResult, req, res);
  });
}

function isStreamingRoute(pathname) {
  if (PAGE_ROUTES.some((route) => route.regex.test(pathname))) {
    return false;
  }
  const apiPath = pathname.replace(/^\\//, "");
  const match = API_ROUTES.find((route) => route.regex.test(apiPath));
  return !!match && match.kind === "serverless-streaming";
}

function serveStatic(req, res, pathname) {
  let decoded;
  try {
    decoded = decodeURIComponent(pathname);
  } catch (error) {
    return false;
  }
  const filePath = path.resolve(
    DIST_DIR,
    "." + (decoded === "/" ? "/index.html" : decoded)
  );
  if (!filePath.startsWith(DIST_DIR + path.sep)) {
    return false;
  }
  let stat;
  try {
    stat = fs.statSync(filePath);
  } catch (error) {
    return false;
  }
  if (!stat.isFile()) {
    return false;
  }
  const ext = path.extname(filePath).toLowerCase();
  res.writeHead(200, {
    "Content-Type": MIME_TYPES[ext] || "application/octet-stream",
    "Content-Length": stat.size,
  });
  if (req.method === "HEAD") {
    res.end();
  } else {
    fs.createReadStream(filePath).pipe(res);
  }
  return true;
}

/**
 * Read the whole body into one Buffer, or answer 413 and resolve undefined
 * when it exceeds MAX_BODY_BYTES. Resolves null for an empty body.
 */
function readBody(req, res) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0;
    let tooLarge = false;
    req.on("data", (chunk) => {
      if (tooLarge) {
        return;
      }
      size += chunk.length;
      if (size > MAX_BODY_BYTES) {
        tooLarge = true;
        chunks.length = 0;
        res.writeHead(413, { "Content-Type": "application/json", Connection: "close" });
        res.end(
          JSON.stringify({
            error: \`Request body over \${MAX_BODY_BYTES} bytes. Only streaming routes (ApiRoute.serverRenderStreaming) take bodies that large.\`,
          })
        );
        resolve(undefined);
        return;
      }
      chunks.push(chunk);
    });
    req.on("end", () => {
      if (!tooLarge) {
        resolve(chunks.length > 0 ? Buffer.concat(chunks) : null);
      }
    });
    req.on("error", (error) => {
      if (!tooLarge) {
        reject(error);
      }
    });
  });
}

function buildRequest(req, body, multiPartFormData) {
  const url = new URL(req.url || "/", \`http://\${req.headers.host || "localhost"}\`);
  return {
    requestTime: Date.now(),
    method: req.method,
    headers: req.headers || {},
    rawUrl: url.toString(),
    body: body,
    multiPartFormData: multiPartFormData,
  };
}

async function buildRequestWithBody(req, bodyBuffer) {
  const body = bodyBuffer ? bodyBuffer.toString("utf-8") : null;
  let multiPartFormData = null;
  if (
    req.method === "POST" &&
    bodyBuffer &&
    (req.headers["content-type"] || "").includes("multipart/form-data")
  ) {
    multiPartFormData = await parseMultipart(req, bodyBuffer);
  }
  const serverRequest = buildRequest(req, body, multiPartFormData);
  if (bodyBuffer) {
    // Binary-safe copy for Stream.requestBody's buffered fallback; kept out of
    // the flags so Elm still decodes body as a string.
    serverRequest.__rawBodyBuffer = bodyBuffer;
  }
  return serverRequest;
}

async function parseMultipart(req, bodyBuffer) {
  try {
    const busboy = (await import("busboy")).default;
    return await new Promise((resolve) => {
      const fields = {};
      const bb = busboy({ headers: req.headers });
      bb.on("file", (fieldname, file, info) => {
        const { filename, mimeType } = info;
        file.on("data", (data) => {
          fields[fieldname] = { filename, mimeType, body: data.toString() };
        });
      });
      bb.on("field", (fieldName, value) => {
        fields[fieldName] = value;
      });
      bb.on("close", () => resolve(fields));
      bb.on("error", () => resolve(null));
      bb.end(bodyBuffer);
    });
  } catch (error) {
    return null;
  }
}

async function sendResponse(renderResult, req, res) {
  const isHead = req.method === "HEAD";
  if (renderResult.kind === "api-response") {
    if (renderResult.streamPipeline) {
      const result = await elmPages.executeStreamToResponse(
        renderResult.streamPipeline,
        res,
        { statusCode: renderResult.statusCode, headers: renderResult.headers }
      );
      if (!result.ok && !res.headersSent) {
        res.writeHead(500, { "Content-Type": "text/plain" });
        res.end("Streaming response error: " + result.error);
      }
      return;
    }
    setHeaders(res, renderResult.headers);
    res.writeHead(renderResult.statusCode);
    if (isHead || renderResult.body == null) {
      res.end();
    } else if (renderResult.isBase64Encoded) {
      res.end(Buffer.from(renderResult.body, "base64"));
    } else {
      res.end(renderResult.body);
    }
  } else if (renderResult.kind === "bytes") {
    // content.dat for client-side navigation: the bundle hands back a Buffer
    setHeaders(res, renderResult.headers);
    res.writeHead(renderResult.statusCode, {
      "Content-Type": "application/octet-stream",
    });
    res.end(isHead ? undefined : toBuffer(renderResult.body));
  } else if (renderResult.kind === "html") {
    setHeaders(res, renderResult.headers);
    res.writeHead(renderResult.statusCode, { "Content-Type": "text/html" });
    res.end(isHead ? undefined : renderResult.body);
  } else {
    res.writeHead(500, { "Content-Type": "text/plain" });
    res.end("Unknown render result kind: " + renderResult.kind);
  }
}

function toBuffer(body) {
  if (Buffer.isBuffer(body)) {
    return body;
  } else if (body instanceof Uint8Array) {
    return Buffer.from(body.buffer, body.byteOffset, body.byteLength);
  } else if (typeof body === "string") {
    return Buffer.from(body, "base64");
  } else {
    return Buffer.alloc(0);
  }
}

function setHeaders(res, headers) {
  if (!headers) return;
  for (const [key, values] of Object.entries(headers)) {
    res.setHeader(key, values);
  }
}

function sendError(req, res, error) {
  if (res.headersSent) {
    res.end();
    return;
  }
  const message =
    typeof error === "string" ? error : (error && error.message) || String(error);
  if ((req.url || "").includes("content.dat") || (req.method !== "GET" && req.method !== "HEAD")) {
    res.writeHead(500, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: message }));
  } else {
    res.writeHead(500, { "Content-Type": "text/html" });
    res.end("<!doctype html><title>Error</title><pre>Internal Server Error</pre>");
  }
}

// On SIGTERM stop taking new connections and let in-flight requests finish,
// for a few seconds at most, so a restart does not cut off a response that is
// moments from done.
function shutdown(signal) {
  console.log(\`elm-pages server: \${signal}, shutting down\`);
  server.close(() => process.exit(0));
  server.closeIdleConnections();
  setTimeout(() => process.exit(0), 5000).unref();
}
process.on("SIGTERM", () => shutdown("SIGTERM"));
process.on("SIGINT", () => shutdown("SIGINT"));

const onListening = () => {
  console.log(
    \`elm-pages server listening on \${HOST ? HOST : "*"}:\${PORT} (static files: \${DIST_DIR})\`
  );
};
if (HOST) {
  server.listen(PORT, HOST, onListening);
} else {
  server.listen(PORT, onListening);
}
`;
}

/**
 * @param {string} dirpath
 */
function ensureDirSync(dirpath) {
  try {
    fs.mkdirSync(dirpath, { recursive: true });
  } catch (err) {
    if (err.code !== "EEXIST") throw err;
  }
}
